const PROFESSION_CHANGE_AMOUNT = 2000;
const PROFESSION_CHANGE_WINDOW_MS = 30 * 24 * 60 * 60 * 1000;
// Temporary test-period switch. Set PROFESSION_CHANGE_TEST_MODE=false to restore
// the monthly limit and Hub2 payment requirement.
const PROFESSION_CHANGE_TEST_MODE =
  process.env.PROFESSION_CHANGE_TEST_MODE?.toLowerCase() !== "false";

// ---------------------------------------------------------------------------
// In-memory delete-token store
//
// Tokens are generated by POST /profile/delete-token and consumed by
// DELETE /profile. They are:
//   - Short-lived (15 minutes)
//   - Single-use (removed from the store on first use)
//   - Never embedded in GET /profile responses
//
// The token maps to the exact profile id it was issued for, so DELETE
// always resolves the profile from the token's stored identity rather
// than an unscoped limit(1) query.
// ---------------------------------------------------------------------------
const DELETE_TOKEN_TTL_MS = 15 * 60 * 1000;

interface StoredDeleteToken {
  profileId: number;
  expiresAt: number;
}

const deleteTokenStore = new Map<string, StoredDeleteToken>();

function issueDeleteToken(profileId: number): { token: string; expiresAt: Date } {
  // Purge expired entries opportunistically
  const now = Date.now();
  for (const [key, entry] of deleteTokenStore) {
    if (entry.expiresAt <= now) deleteTokenStore.delete(key);
  }
  const token = randomBytes(32).toString("hex");
  const expiresAt = new Date(now + DELETE_TOKEN_TTL_MS);
  deleteTokenStore.set(token, { profileId, expiresAt: expiresAt.getTime() });
  return { token, expiresAt };
}

function consumeDeleteToken(token: string): number | null {
  const entry = deleteTokenStore.get(token);
  if (!entry) return null;
  deleteTokenStore.delete(token); // Single-use: always remove after first lookup
  if (entry.expiresAt <= Date.now()) return null;
  return entry.profileId;
}

function professionChangeAvailableAt(lastChangeAt: Date | null): Date | null {
  if (!lastChangeAt) return null;
  const availableAt = new Date(lastChangeAt.getTime() + PROFESSION_CHANGE_WINDOW_MS);
  return availableAt.getTime() <= Date.now() ? null : availableAt;
}

function isPlaceholderProfileName(value: string | null | undefined): boolean {
  const normalized = value?.trim().toLocaleLowerCase("fr-FR") ?? "";
  return !normalized || normalized === "nouveau candidat" || normalized === "utilisateur" || normalized === "new candidate";
}

function fullNameFromCvAnalysis(value: unknown): string | null {
  if (!value || typeof value !== "object") return null;
  const fullName = (value as { fullName?: unknown }).fullName;
  return typeof fullName === "string" && !isPlaceholderProfileName(fullName) ? fullName.trim() : null;
}

function makeProfessionPurchaseReference(profileId: number): string {
  return `JOBAGOGO_PROFESSION_${profileId}_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
}

function professionPaymentJson(
  payment: typeof professionChangePaymentsTable.$inferSelect,
  checkoutUrl: string,
) {
  const environment = hub2Environment();
  return {
    id: payment.id,
    amount: payment.amount,
    status: payment.status,
    checkoutUrl,
    purchaseReference: payment.purchaseReference,
    paymentLinkExpiresAt: payment.paymentLinkExpiresAt?.toISOString() ?? null,
    environment,
    sandboxTestPhone: environment === "sandbox" ? "00000001" : null,
  };
}

function profileShape(profile: typeof profilesTable.$inferSelect, isDemo = false) {
  const premiumStatus = getPremiumTrialStatus(profile);

  return {
    id: profile.id,
    name: profile.name,
    title: profile.title,
    skills: profile.skills,
    experienceYears: profile.experienceYears,
    location: profile.location,
    remote: profile.remote,
    jobTypes: profile.jobTypes,
    salaryMin: profile.salaryMin,
    salaryMax: profile.salaryMax,
    bio: profile.bio,
    email: profile.email,
    linkedin: profile.linkedin,
    phone: profile.phone,
    diploma: profile.diploma,
    lastJobTitle: profile.lastJobTitle,
    profilePhoto: profile.profilePhoto,
    notificationsEnabled: profile.notificationsEnabled,
    lastProfessionChangeAt: profile.lastProfessionChangeAt?.toISOString() ?? null,
    professionChangeAvailableAt: PROFESSION_CHANGE_TEST_MODE
      ? null
      : professionChangeAvailableAt(profile.lastProfessionChangeAt)?.toISOString() ?? null,
    isPremium: premiumStatus.isPremium,
    premiumUntil: profile.premiumUntil?.toISOString() ?? null,
    premiumTrialUntil: profile.premiumTrialUntil?.toISOString() ?? null,
    isPremiumTrial: premiumStatus.isPremiumTrial,
    isPremiumTrialExpired: premiumStatus.isPremiumTrialExpired,
    updatedAt: profile.updatedAt.toISOString(),
    // Whether a device credential (SHA-256 hash) is stored for this account.
    // The mobile client uses this to decide whether to show the in-app delete
    // flow or a "contact support" message for accounts created before this
    // feature was introduced.
    isDeviceRegistered: profile.deviceSecretHash !== null,
    isDemo,
  };
}

router.get("/profile", async (req, res): Promise<void> => {
  const profiles = await db.select().from(profilesTable)
    .where(eq(profilesTable.id, req.auth!.profileId))
    .limit(1);
  if (!profiles[0]) {
    res.status(404).json({ error: "No profile found" });
    return;
  }
  const [latestCv] = await db.select({
    id: cvDocumentsTable.id,
    fileName: cvDocumentsTable.fileName,
    status: cvDocumentsTable.status,
    analysis: cvDocumentsTable.analysis,
    createdAt: cvDocumentsTable.createdAt,
  }).from(cvDocumentsTable)
    .where(eq(cvDocumentsTable.profileId, profiles[0].id))
    .orderBy(desc(cvDocumentsTable.createdAt))
    .limit(1);
  let profileForResponse = profiles[0];
  const inferredName = isPlaceholderProfileName(profileForResponse.name)
    ? fullNameFromCvAnalysis(latestCv?.analysis)
    : null;
  if (inferredName) {
    const [updatedProfile] = await db.update(profilesTable)
      .set({ name: inferredName })
      .where(eq(profilesTable.id, profileForResponse.id))
      .returning();
    profileForResponse = updatedProfile ?? { ...profileForResponse, name: inferredName };
  }

  res.json({ ...profileShape(profileForResponse, req.auth!.isDemo), latestCv: latestCv ? {
    ...latestCv,
    createdAt: latestCv.createdAt.toISOString(),
  } : null });
});

router.post("/profile", requireNonDemo, async (req, res): Promise<void> => {
  const parsed = UpsertProfileBody.safeParse(req.body);
  if (!parsed.success) {
    res.status(400).json({ error: parsed.error.message });
    return;
  }

  const existing = await db.select().from(profilesTable)
    .where(eq(profilesTable.id, req.auth!.profileId))
    .limit(1);

  let profile;
  if (existing[0]) {
    // UPDATE path: never touch deviceSecretHash here.
    // The deletion credential is established at profile creation and can only
    // be registered afterwards via POST /profile/register-device, which only
    // works when no hash is stored yet. This prevents an unauthenticated
    // caller from overwriting the credential via a profile update.
    const currentProfile = existing[0];
    const requestedTitle = parsed.data.title?.trim() ?? "";
    const currentTitle = currentProfile.title?.trim() ?? "";
    const professionChanged = requestedTitle !== currentTitle;
    const availableAt = professionChangeAvailableAt(currentProfile.lastProfessionChangeAt);

    if (professionChanged && availableAt && !PROFESSION_CHANGE_TEST_MODE) {
      res.status(409).json({
        error: "Changer de métier avant la fin du mois nécessite un paiement de 2 000 XOF.",
        code: "PROFESSION_CHANGE_PAYMENT_REQUIRED",
        professionChangeAvailableAt: availableAt.toISOString(),
        amount: PROFESSION_CHANGE_AMOUNT,
      });
      return;
    }

    const updated = await db
      .update(profilesTable)
      .set({
        ...parsed.data,
        email: currentProfile.email,
        emailVerifiedAt: currentProfile.emailVerifiedAt,
        skills: parsed.data.skills ?? [],
        jobTypes: parsed.data.jobTypes ?? [],
        ...(professionChanged ? { lastProfessionChangeAt: new Date() } : {}),
      })
      .where(eq(profilesTable.id, existing[0].id))
      .returning();
    profile = updated[0];
  } else {
    const premiumTrial = createPremiumTrial();
    const inserted = await db
      .insert(profilesTable)
      .values({
        ...parsed.data,
        email: req.auth!.email,
        emailVerifiedAt: new Date(),
        ...premiumTrial,
        skills: parsed.data.skills ?? [],
        jobTypes: parsed.data.jobTypes ?? [],
      })
      .returning();
    profile = inserted[0];
  }

  res.json(profileShape(profile));
});

