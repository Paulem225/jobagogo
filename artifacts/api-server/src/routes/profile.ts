router.post("/profile/profession-change/payments", requireNonDemo, async (req, res): Promise<void> => {
  if (PROFESSION_CHANGE_TEST_MODE) {
    res.status(400).json({
      error: "Le changement de métier est gratuit pendant la période de test.",
    });
    return;
  }

  const requestedTitle = typeof req.body?.title === "string" ? req.body.title.trim() : "";
  if (!requestedTitle) {
    res.status(400).json({ error: "Le nouveau métier est obligatoire." });
    return;
  }

  const [profile] = await db.select().from(profilesTable)
    .where(eq(profilesTable.id, req.auth!.profileId))
    .limit(1);
  if (!profile) {
    res.status(404).json({ error: "Profil introuvable" });
    return;
  }

  const currentTitle = profile.title?.trim() ?? "";
  const availableAt = professionChangeAvailableAt(profile.lastProfessionChangeAt);
  if (!currentTitle || requestedTitle === currentTitle || !availableAt) {
    res.status(400).json({ error: "Ce changement de métier ne nécessite pas de paiement." });
    return;
  }

  const purchaseReference = makeProfessionPurchaseReference(profile.id);
  const expirationDate = new Date(Date.now() + 30 * 60 * 1000);
  let hub2Response: Response;
  try {
    hub2Response = await fetch("https://api.hub2.io/payment-links", {
      method: "POST",
      headers: hub2Headers(),
      body: JSON.stringify({
        purchaseReference,
        description: `Changement de métier Jobagogo : ${requestedTitle}`,
        amount: PROFESSION_CHANGE_AMOUNT,
        currency: "XOF",
        country: process.env["HUB2_COUNTRY"] ?? "CI",
        type: "single_use",
        expirationDate: expirationDate.toISOString(),
        paymentMethods: ["mobile_money"],
        providers: ["Orange", "MTN", "Moov", "Wave"],
      }),
    });
  } catch (error) {
    req.log.error({ err: error }, "Hub2 profession change payment request failed");
    res.status(502).json({ error: "Impossible de joindre Hub2" });
    return;
  }

  if (!hub2Response.ok) {
    req.log.error({
      status: hub2Response.status,
      body: await hub2Response.text(),
    }, "Hub2 rejected profession change payment");
    res.status(502).json({ error: "Hub2 a refusé la création du paiement" });
    return;
  }

  const hub2PaymentLink = await hub2Response.json() as { id?: string; url?: string };
  if (!hub2PaymentLink.id || !hub2PaymentLink.url) {
    res.status(502).json({ error: "Réponse Hub2 invalide" });
    return;
  }

  const [payment] = await db.insert(professionChangePaymentsTable).values({
    profileId: profile.id,
    hub2PaymentLinkId: hub2PaymentLink.id,
    purchaseReference,
    requestedTitle,
    amount: PROFESSION_CHANGE_AMOUNT,
    paymentLinkExpiresAt: expirationDate,
  }).returning();

  res.status(201).json(professionPaymentJson(payment, hub2PaymentLink.url));
});

router.get("/profile/profession-change/payments/:paymentId/status", requireNonDemo, async (req, res): Promise<void> => {
  const paymentId = Number(req.params["paymentId"]);
  if (!Number.isInteger(paymentId)) {
    res.status(400).json({ error: "Identifiant de paiement invalide" });
    return;
  }

  const [payment] = await db.select()
    .from(professionChangePaymentsTable)
    .where(and(
      eq(professionChangePaymentsTable.id, paymentId),
      eq(professionChangePaymentsTable.profileId, req.auth!.profileId),
    ))
    .limit(1);
  if (!payment) {
    res.status(404).json({ error: "Paiement introuvable" });
    return;
  }

  let hub2Response: Response;
  try {
    hub2Response = await fetch(
      `https://api.hub2.io/payment-links/${encodeURIComponent(payment.hub2PaymentLinkId)}`,
      { headers: hub2Headers() },
    );
  } catch (error) {
    req.log.error({ err: error, paymentId }, "Hub2 profession change status request failed");
    res.status(502).json({ error: "Impossible de vérifier le paiement auprès de Hub2" });
    return;
  }

  if (!hub2Response.ok) {
    res.status(502).json({ error: "Hub2 n'a pas pu vérifier le paiement" });
    return;
  }

  const hub2PaymentLink = await hub2Response.json();
  const { status, failureReason } = paymentStatusFromHub2(hub2PaymentLink);
  const completed = status === "completed";

  if (completed && payment.status !== "completed") {
    await db.update(professionChangePaymentsTable)
      .set({ status: "completed" })
      .where(eq(professionChangePaymentsTable.id, payment.id));
    await db.update(profilesTable)
      .set({ title: payment.requestedTitle, lastProfessionChangeAt: new Date() })
      .where(eq(profilesTable.id, payment.profileId));
  } else if (!completed && status !== payment.status) {
    await db.update(professionChangePaymentsTable)
      .set({ status })
      .where(eq(professionChangePaymentsTable.id, payment.id));
  }

  res.json({
    id: payment.id,
    status: completed ? "completed" : status,
    title: payment.requestedTitle,
    failureReason: status === "failed" ? failureReasonLabel(failureReason) : null,
    message: completed
      ? "Paiement confirmé. Le métier a été changé."
      : status === "failed"
        ? failureReasonLabel(failureReason)
        : "Paiement en attente de confirmation.",
  });
});

// POST /profile/delete-token — issues a short-lived, single-use token that
// the client must present to DELETE /profile. The token is stored server-side
// and is never embedded in the GET /profile response.
//
// Primary authentication is the verified email session. The old device secret
// remains on clients only for compatibility with older builds.
//
router.post("/profile/delete-token", requireNonDemo, async (req, res): Promise<void> => {
  const [profile] = await db.select().from(profilesTable)
    .where(eq(profilesTable.id, req.auth!.profileId))
    .limit(1);
  if (!profile) {
    res.status(404).json({ error: "No profile found" });
    return;
  }

  const { token, expiresAt } = issueDeleteToken(profile.id);
  res.json({ token, expiresAt: expiresAt.toISOString() });
});

// DELETE /profile — permanently purges the profile and all associated data.
// The authenticated session remains in Authorization; the short-lived
// confirmation token is sent separately so the auth middleware can still
// identify the account. The token is single-use and must belong to the same
// profile as the session.
router.delete("/profile", requireNonDemo, async (req, res): Promise<void> => {
  const rawToken = req.headers["x-delete-token"];
  if (typeof rawToken !== "string" || rawToken.length === 0) {
    res.status(401).json({ error: "Token de confirmation requis." });
    return;
  }
  const profileId = consumeDeleteToken(rawToken);
  if (!profileId || profileId !== req.auth!.profileId) {
    res.status(401).json({ error: "Token de suppression invalide, expiré ou déjà utilisé." });
    return;
  }

  const [profile] = await db
    .select()
    .from(profilesTable)
    .where(eq(profilesTable.id, profileId))
    .limit(1);
  if (!profile) {
    res.status(404).json({ error: "No profile found" });
    return;
  }

  // Purge all profile data in a single transaction so a partial failure
  // never leaves the account in an inconsistent state.
  await db.transaction(async (tx) => {
    await tx.delete(cvDocumentsTable).where(eq(cvDocumentsTable.profileId, profile.id));
    await tx.delete(premiumPaymentsTable).where(eq(premiumPaymentsTable.profileId, profile.id));
    await tx.delete(professionChangePaymentsTable).where(eq(professionChangePaymentsTable.profileId, profile.id));
    await tx.delete(savedJobsTable).where(eq(savedJobsTable.profileId, profile.id));
    await tx.delete(profilesTable).where(eq(profilesTable.id, profile.id));
  });

  res.status(204).end();
});

