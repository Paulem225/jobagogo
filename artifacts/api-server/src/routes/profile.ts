router.post("/profile/notifications", requireNonDemo, async (req, res): Promise<void> => {
  const parsed = RegisterProfileNotificationsBody.safeParse(req.body);
  if (!parsed.success) {
    res.status(400).json({ error: parsed.error.message });
    return;
  }

  const [profile] = await db.select().from(profilesTable)
    .where(eq(profilesTable.id, req.auth!.profileId))
    .limit(1);
  if (!profile) {
    res.status(404).json({ error: "No profile found" });
    return;
  }

  const enabled = parsed.data.enabled && Boolean(parsed.data.token);
  if (enabled && (!parsed.data.token || !isFirebasePushToken(parsed.data.token))) {
    res.status(400).json({
      error: "Le token Firebase est invalide. Réessaie depuis une build mobile récente.",
    });
    return;
  }

  if (enabled && parsed.data.token) {
    await db
      .insert(pushDevicesTable)
      .values({
        profileId: profile.id,
        token: parsed.data.token,
        platform: parsed.data.platform ?? "android",
        enabled: true,
        lastSeenAt: new Date(),
      })
      .onConflictDoUpdate({
        target: pushDevicesTable.token,
        set: {
          profileId: profile.id,
          platform: parsed.data.platform ?? "android",
          enabled: true,
          lastSeenAt: new Date(),
          updatedAt: new Date(),
        },
      });
  } else if (parsed.data.token) {
    await db
      .update(pushDevicesTable)
      .set({ enabled: false, updatedAt: new Date() })
      .where(
        and(
          eq(pushDevicesTable.profileId, profile.id),
          eq(pushDevicesTable.token, parsed.data.token),
        ),
      );
  } else {
    await db
      .update(pushDevicesTable)
      .set({ enabled: false, updatedAt: new Date() })
      .where(eq(pushDevicesTable.profileId, profile.id));
  }

  const [activeDevice] = await db
    .select({ id: pushDevicesTable.id })
    .from(pushDevicesTable)
    .where(
      and(
        eq(pushDevicesTable.profileId, profile.id),
        eq(pushDevicesTable.enabled, true),
      ),
    )
    .limit(1);

  await db
    .update(profilesTable)
    .set({ notificationsEnabled: Boolean(activeDevice) })
    .where(eq(profilesTable.id, profile.id));

  res.json({ enabled: Boolean(activeDevice), provider: "firebase" as const });
});

